DROP TABLE OrderItems CASCADE CONSTRAINTS;
DROP TABLE TicketTypes CASCADE CONSTRAINTS;
DROP TABLE Orders CASCADE CONSTRAINTS;
DROP TABLE Events CASCADE CONSTRAINTS;
DROP TABLE Categories CASCADE CONSTRAINTS;
DROP TABLE Venues CASCADE CONSTRAINTS;
DROP TABLE Organizers CASCADE CONSTRAINTS;
DROP TABLE Users CASCADE CONSTRAINTS;

-- 1. Utilizatori
CREATE TABLE Users (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume NVARCHAR2(100) NOT NULL,
    Email NVARCHAR2(100) NOT NULL UNIQUE,
    ParolaHash NVARCHAR2(255) NOT NULL
);

-- 2. Organizatori
CREATE TABLE Organizers (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NumeCompanie NVARCHAR2(150) NOT NULL,
    CUI NVARCHAR2(20) UNIQUE,
    ContactEmail NVARCHAR2(100)
);

-- 3. Locatii
CREATE TABLE Venues (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume NVARCHAR2(100) NOT NULL,
    Adresa NVARCHAR2(255) NOT NULL,
    Oras NVARCHAR2(50) NOT NULL,
    CapacitateMaxima NUMBER(10) NOT NULL CHECK(CapacitateMaxima > 0)
);

-- 4. Categorii
CREATE TABLE Categories (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NumeCategorie NVARCHAR2(50) NOT NULL UNIQUE
);

-- 5. Evenimente
CREATE TABLE Events (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Titlu NVARCHAR2(150) NOT NULL,
    Descriere NCLOB,
    DataEveniment TIMESTAMP NOT NULL,
    ID_Locatie NUMBER(10) NOT NULL,
    ID_Organizator NUMBER(10) NOT NULL,
    ID_Categorie NUMBER(10) NOT NULL,
    CONSTRAINT fk_events_venues FOREIGN KEY (ID_Locatie) REFERENCES Venues(ID),
    CONSTRAINT fk_events_organizers FOREIGN KEY (ID_Organizator) REFERENCES Organizers(ID),
    CONSTRAINT fk_events_categories FOREIGN KEY (ID_Categorie) REFERENCES Categories(ID)
);

-- 6. Comenzi
CREATE TABLE Orders (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Utilizator NUMBER(10) NOT NULL,
    DataComenzii TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    StatusComanda NVARCHAR2(20) DEFAULT 'Procesata' NOT NULL,
    Total NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_orders_users FOREIGN KEY (ID_Utilizator) REFERENCES Users(ID)
);

-- 7. Tipuri de bilete
CREATE TABLE TicketTypes (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Eveniment NUMBER(10) NOT NULL,
    NumeTip NVARCHAR2(50) NOT NULL,
    Pret NUMBER(10, 2) NOT NULL CHECK(Pret >= 0),
    CantitateTotala NUMBER(10) NOT NULL CHECK(CantitateTotala > 0),
    CONSTRAINT fk_tickettypes_events FOREIGN KEY (ID_Eveniment) REFERENCES Events(ID) ON DELETE CASCADE
);

-- 8. Elemente Comanda
CREATE TABLE OrderItems (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Comanda NUMBER(10) NOT NULL,
    ID_TipBilet NUMBER(10) NOT NULL,
    Cantitate NUMBER(5) NOT NULL CHECK(Cantitate > 0),
    PretLaCumparare NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_orderitems_orders FOREIGN KEY (ID_Comanda) REFERENCES Orders(ID) ON DELETE CASCADE,
    CONSTRAINT fk_orderitems_tickettypes FOREIGN KEY (ID_TipBilet) REFERENCES TicketTypes(ID)
);